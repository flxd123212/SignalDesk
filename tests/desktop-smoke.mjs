import { electronExecutable } from '../desktop/platform.cjs';
import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';
import os from 'node:os';

const environment = { ...process.env };
const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'signaldesk-desktop-test-'));
environment.SIGNALDESK_USER_DATA = directory;
delete environment.ELECTRON_RUN_AS_NODE;
const desktop = await electron.launch({ executablePath: electronExecutable(process.cwd()), args: ['.'], cwd: process.cwd(), env: environment, timeout: 30000 });
try {
  const window = await desktop.firstWindow();
  await window.getByRole('heading', { name: '实时监测', exact: true }).waitFor();
  const startup = await window.evaluate(async () => (await fetch('/api/state')).json());
  assert.equal(startup.connected, false); assert.equal(startup.config.path, 'unassigned');
  assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isMenuBarVisible()), false);
  assert.equal(await window.locator('.app-header').evaluate(element => getComputedStyle(element).getPropertyValue('-webkit-app-region')), 'drag');
  assert.equal(await window.locator('.global-search').evaluate(element => getComputedStyle(element).getPropertyValue('-webkit-app-region')), 'no-drag');
  assert.equal((await window.locator('.app-header').boundingBox()).height, 40);
  const caption = await window.evaluate(() => navigator.windowControlsOverlay?.getTitlebarAreaRect().toJSON());
  assert.ok(caption && caption.width > 0 && caption.width < 1500, 'Native caption buttons reserve titlebar space');
  await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(780, 760));
  await window.waitForFunction(() => innerWidth <= 780);
  assert.equal(await window.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await window.locator('.header-right').evaluate(element => element.getBoundingClientRect().right <= navigator.windowControlsOverlay.getTitlebarAreaRect().width), true);
  await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1500, 980));
  await window.waitForFunction(() => innerWidth > 1000);
  await window.screenshot({ path: path.resolve('artifacts/integrated-titlebar.png') });
  await window.locator('.header-right').getByRole('button', { name: '发现设备', exact: true }).click();
  await window.getByRole('dialog', { name: '发现设备', exact: true }).waitFor();
  await window.getByRole('button', { name: '关闭设备发现', exact: true }).click();
  await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].maximize());
  await window.waitForFunction(() => innerWidth > 1500);
  assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isMaximized()), true);
  await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].unmaximize());
  await window.evaluate(async () => fetch('/api/connect', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ path: 'demo' }) }));
  await window.waitForFunction(() => Number(document.querySelector('.plot-footer')?.textContent?.match(/([\d,]+) frames/)?.[1].replaceAll(',', '') || 0) > 1000, null, { timeout: 20000 });
  assert.equal(await window.locator('.uplot canvas').count(), 1);
  assert.equal(await window.getByRole('button', { name: '发送', exact: true }).isEnabled(), true);
  const before = await window.locator('.uplot canvas').evaluate(canvas => canvas.toDataURL());
  await window.waitForFunction(initial => document.querySelector('.uplot canvas')?.toDataURL() !== initial, before);
  await window.screenshot({ path: path.resolve('artifacts/desktop-native.png') });
  const fullscreen = () => desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isFullScreen());
  const key = value => desktop.evaluate(({ BrowserWindow }, keyCode) => { const contents = BrowserWindow.getAllWindows()[0].webContents; contents.sendInputEvent({ type: 'keyDown', keyCode }); contents.sendInputEvent({ type: 'keyUp', keyCode }); }, value);
  await key('F11'); await window.waitForFunction(() => document.querySelector('[aria-label="退出全屏 (Esc / F11)"]'));
  assert.equal(await fullscreen(), true); await key('Escape');
  await window.waitForFunction(() => document.querySelector('[aria-label="全屏 (F11)"]')); assert.equal(await fullscreen(), false);
  await window.getByRole('button', { name: '全屏 (F11)', exact: true }).click();
  await window.getByRole('button', { name: '退出全屏 (Esc / F11)', exact: true }).waitFor(); await key('F11');
  await window.waitForFunction(() => document.querySelector('[aria-label="全屏 (F11)"]'));
  await desktop.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, directory);
  await window.getByRole('button', { name: '视图', exact: true }).click(); await window.getByRole('menuitem', { name: '连接设置', exact: true }).click(); await window.locator('.project-summary').click(); await window.getByRole('button', { name: '选择工程目录', exact: true }).click();
  assert.equal(await window.getByLabel('设备工程目录', { exact: true }).inputValue(), directory);
  await window.getByRole('dialog', { name: '设备与工程设置' }).screenshot({ path: path.resolve('artifacts/native-project-picker.png') });
  await key('Escape'); await window.getByRole('dialog', { name: '设备与工程设置' }).waitFor({ state: 'hidden' });
  await desktop.evaluate(({ dialog }, root) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [root] }); }, path.resolve('firmware-examples/SignalGenerator'));
  await window.getByRole('button', { name: '添加项目', exact: true }).click();
  const setup = window.getByRole('dialog', { name: '添加项目', exact: true });
  await setup.getByRole('button', { name: '浏览项目目录', exact: true }).click();
  await setup.getByLabel('项目匹配串口').selectOption('');
  await setup.getByRole('button', { name: '添加项目', exact: true }).click();
  await setup.waitFor({ state: 'hidden' });
  const imported = await window.evaluate(async () => (await fetch('/api/state')).json());
  assert.equal(imported.config.path, 'unassigned'); assert.equal(imported.connected, false); assert.equal(imported.devices.length, 2);
  await window.getByRole('tab').first().click();
  await window.getByRole('button', { name: '工具', exact: true }).click(); await window.getByRole('menuitem', { name: '实时监测', exact: true }).click();
  for (const exit of ['Escape', 'F11']) {
    await window.getByRole('button', { name: '全屏波形', exact: true }).click();
    await window.waitForFunction(() => Boolean(document.fullscreenElement));
    await window.getByRole('button', { name: '退出波形全屏 (Esc / F11)', exact: true }).waitFor();
    await key(exit); await window.waitForFunction(() => !document.fullscreenElement);
  }
  await window.getByRole('button', { name: '工具', exact: true }).click(); await window.getByRole('menuitem', { name: 'AI 与 Agent', exact: true }).click();
  await window.getByRole('button', { name: '分析数据', exact: true }).click();
  await window.getByText('本地分析', { exact: true }).waitFor();
  const nextWindow = desktop.waitForEvent('window');
  await window.getByRole('button', { name: '文件', exact: true }).click();
  await window.getByRole('menuitem', { name: '新建独立工作区窗口', exact: true }).click();
  const second = await nextWindow;
  await second.getByRole('heading', { name: '实时监测', exact: true }).waitFor();
  assert.notEqual(new URL(window.url()).port, new URL(second.url()).port);
  console.log('Native desktop: waveform, Agent, isolated windows, F11/Esc/fullscreen button, secure project picker and automatic offline project import passed.');
} finally { await desktop.close(); await fs.rm(directory, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }); }

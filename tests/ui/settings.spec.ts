import { test, expect } from '@playwright/test';
import { clickWorkbench } from './workbench-actions';

test('settings customize workspace, persist, import/export and render on small screens', async ({ page }) => {
  await page.goto('/?view=agent');
  await expect(page.locator('.agent-execution')).not.toBeVisible();
  await expect(page.locator('.context-sendbar')).not.toBeVisible();
  await expect(page.locator('.layout-shortcuts')).not.toBeVisible();
  await expect(page.getByRole('navigation', { name: '工作区导航' }).getByRole('button')).toHaveCount(10);
  await page.getByRole('button', { name: '项目体检', exact: true }).click();
  await expect(page.locator('.agent-message.assistant')).toContainText('项目体检');
  await page.screenshot({ path: 'artifacts/settings-agent-clean.png', fullPage: true });
  await page.getByRole('button', { name: /^串口发送/ }).click();
  await expect(page.locator('.context-sendbar')).toBeVisible();
  await page.keyboard.press('Control+,');
  const settings = page.getByRole('dialog', { name: '设置', exact: true });
  await expect(settings).toBeVisible();
  await expect(settings).toHaveCSS('animation-name', 'surface-enter');
  await settings.getByLabel('界面动画', { exact: true }).uncheck();
  await expect(page.locator('.app-shell')).toHaveAttribute('data-motion', 'off');
  await expect(settings).toHaveCSS('animation-name', 'none');
  await settings.getByLabel('串口发送栏显示方式').selectOption('hidden');
  await expect(page.locator('.context-sendbar')).not.toBeVisible();
  await settings.getByLabel('串口发送栏显示方式').selectOption('auto');
  await settings.getByRole('button', { name: '晴空蓝', exact: true }).click();
  await settings.getByLabel('固定 CAN 分析', { exact: true }).check();
  await settings.getByLabel('默认启动页').selectOption('editor');
  const download = page.waitForEvent('download'); await settings.getByRole('button', { name: '导出偏好', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('signaldesk-preferences.json');
  await settings.getByRole('button', { name: '代码编辑器', exact: true }).click();
  await settings.getByLabel('代码字号').selectOption('18');
  await settings.getByLabel('代码自动换行').uncheck();
  await page.screenshot({ path: 'artifacts/settings-editor.png' });
  await settings.getByRole('button', { name: 'AI 接口', exact: true }).click();
  await expect(settings.getByLabel('AI 模型名称')).toBeVisible();
  await expect(settings.getByLabel('固件项目目录')).not.toBeVisible();
  await settings.getByRole('button', { name: '编译工具链', exact: true }).click();
  await expect(settings.getByLabel('工程构建工具')).toBeVisible();
  await page.keyboard.press('Escape'); await expect(settings).toHaveCount(0);
  await page.goto('/'); await expect(page.locator('.editor-page')).toBeVisible();
  await expect(page.locator('.app-shell')).toHaveAttribute('data-motion', 'off');
  await expect(page.getByRole('button', { name: 'CAN 分析', exact: true })).toBeVisible();
  await expect(page.locator('.app-shell')).toHaveCSS('--accent', '#87bfff');
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  await settings.getByLabel('界面动画', { exact: true }).check();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(settings).toHaveCSS('animation-name', 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await settings.getByLabel('导入偏好文件').setInputFiles({ name: 'prefs.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, preferences: { accent: '#73d8bb', favorites: [], editorSize: 16, apiKey: 'should-not-store' } })) });
  expect(await page.evaluate(() => localStorage.getItem('signaldesk.preferences.v1'))).not.toContain('should-not-store');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(settings).toBeVisible();
  expect(await settings.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: 'artifacts/settings-mobile.png', fullPage: true });
  await settings.getByRole('button', { name: '关闭设置', exact: true }).click();
  await clickWorkbench(page, 'CAN 分析');
  await expect(page.getByRole('heading', { name: 'CAN 分析', exact: true })).toBeVisible();
});

test('detached page shares acquisition and closes without stopping parent', async ({ page, request }) => {
  await request.post('/api/connect', { data: { path: 'demo' } });
  await page.goto('/');
  const opened = page.waitForEvent('popup');
  await page.getByRole('button', { name: '在独立窗口打开当前页', exact: true }).click();
  const popup = await opened;
  await expect(popup.locator('.uplot canvas')).toBeVisible();
  await expect(popup.locator('.navigation')).not.toBeVisible();
  expect(new URL(popup.url()).origin).toBe(new URL(page.url()).origin);
  const before = (await (await request.get('/api/state')).json()).frames;
  await popup.close();
  await expect.poll(async () => (await (await request.get('/api/state')).json()).frames).toBeGreaterThan(before);
});
